export const tr = (key, params) => {
  let text = TEXT[isZh() ? "zh" : "en"][key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) text = text.replaceAll(`{${k}}`, String(v));
  }
  return text;
};
